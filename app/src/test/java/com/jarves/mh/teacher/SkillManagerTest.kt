package com.jarves.mh.teacher

import org.junit.Assert.*
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder
import java.io.File

class SkillManagerTest {

    @get:Rule
    val tempFolder = TemporaryFolder()

    @Test
    fun `test parse standard SKILL markdown with frontmatter`() {
        val manager = SkillManager(tempFolder.root)
        val content = """
            ---
            name: "Calculus Derivations"
            version: "1.2.0"
            description: "Guides student through epsilon-delta proofs and differentiation rules"
            author: "math-dept"
            enabled: true
            permissions: "MATH_EXEC, SCRATCHPAD_WRITE"
            ---
            
            # Instructions
            When deriving derivatives, always begin with the difference quotient:
            lim_{h -> 0} (f(x+h) - f(x)) / h.
        """.trimIndent()

        val skill = manager.parseSkillMarkdown("calc-deriv", content)
        assertEquals("calc-deriv", skill.id)
        assertEquals("Calculus Derivations", skill.name)
        assertEquals("1.2.0", skill.version)
        assertEquals("Guides student through epsilon-delta proofs and differentiation rules", skill.description)
        assertTrue(skill.isEnabled)
        assertEquals(setOf("MATH_EXEC", "SCRATCHPAD_WRITE"), skill.allowedPermissions)
        assertTrue(skill.instructions.contains("difference quotient"))
    }

    @Test
    fun `test save and list skills from directory`() {
        val manager = SkillManager(tempFolder.root)
        val skill = SkillDefinition(
            id = "python-debug",
            name = "Python Debugging Assistant",
            description = "Diagnoses Tracebacks and runtime exceptions",
            instructions = "Inspect the stack trace starting from the deepest call.",
        )

        manager.saveSkill(skill)
        val listed = manager.listSkills()

        assertEquals(1, listed.size)
        assertEquals("python-debug", listed[0].id)
        assertEquals("Python Debugging Assistant", listed[0].name)
    }

    @Test
    fun `test evolution rollback on verification test failure`() {
        val manager = SkillManager(tempFolder.root)
        val baseSkill = SkillDefinition(
            id = "auto-refactor",
            name = "Refactor Tool",
            description = "Stable initial version",
            instructions = "Initial instructions",
        )
        manager.saveSkill(baseSkill)

        val evolvedSkill = baseSkill.copy(
            description = "Evolved with potential regression",
            instructions = "Experimental buggy instructions",
        )

        val success = manager.evolveSkill(
            skill = evolvedSkill,
            testRunner = { false },
        )

        assertFalse("Evolution should report failure", success)

        val rolledBack = manager.listSkills().first { it.id == "auto-refactor" }
        assertEquals("Stable initial version", rolledBack.description)
    }

    @Test
    fun `test evolution commits when test passes`() {
        val manager = SkillManager(tempFolder.root)
        val baseSkill = SkillDefinition(
            id = "good-evolution",
            name = "Good Tool",
            description = "V1",
            instructions = "V1 instructions",
        )
        manager.saveSkill(baseSkill)

        val success = manager.evolveSkill(
            skill = baseSkill.copy(description = "V2 Verified"),
            testRunner = { true },
        )

        assertTrue("Evolution should succeed", success)
        val updated = manager.listSkills().first { it.id == "good-evolution" }
        assertEquals("V2 Verified", updated.description)
        assertTrue(updated.isAutoGenerated)
    }
}
