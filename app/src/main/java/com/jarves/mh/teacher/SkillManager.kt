package com.jarves.mh.teacher

import java.io.File
import java.util.concurrent.ConcurrentHashMap

class SkillManager(
    private val skillsDir: File,
) {
    private val skillCache = ConcurrentHashMap<String, SkillDefinition>()
    @Volatile
    private var isCacheLoaded = false

    init {
        skillsDir.mkdirs()
    }

    fun listSkills(): List<SkillDefinition> {
        if (isCacheLoaded) {
            return skillCache.values.sortedBy { it.name }
        }
        val skillDirs = skillsDir.listFiles { f -> f.isDirectory } ?: return emptyList()
        val list = ArrayList<SkillDefinition>(skillDirs.size)
        for (dir in skillDirs) {
            loadSkill(dir)?.let {
                skillCache[it.id] = it
                list.add(it)
            }
        }
        isCacheLoaded = true
        return list.sortedBy { it.name }
    }

    fun loadSkill(skillDirectory: File): SkillDefinition? {
        val skillFile = File(skillDirectory, "SKILL.md")
        if (!skillFile.isFile) return null

        val content = skillFile.readText()
        val skill = parseSkillMarkdown(skillDirectory.name, content, skillDirectory)
        skillCache[skill.id] = skill
        return skill
    }

    fun parseSkillMarkdown(id: String, content: String, baseDir: File? = null): SkillDefinition {
        var name = id
        var version = "1.0.0"
        var description = ""
        val permissions = mutableSetOf<String>()
        var isEnabled = true
        var isAutoGenerated = false
        var author = "user"
        var sourceUrl: String? = null

        val lines = content.lines()
        var bodyStartIndex = 0

        if (lines.firstOrNull()?.trim() == "---") {
            var frontmatterEnd = -1
            for (i in 1 until lines.size) {
                if (lines[i].trim() == "---") {
                    frontmatterEnd = i
                    break
                }
            }

            if (frontmatterEnd != -1) {
                bodyStartIndex = frontmatterEnd + 1
                for (i in 1 until frontmatterEnd) {
                    val line = lines[i]
                    val colon = line.indexOf(':')
                    if (colon > 0) {
                        val key = line.substring(0, colon).trim().lowercase()
                        val value = line.substring(colon + 1).trim().removeSurrounding("\"").removeSurrounding("'")
                        when (key) {
                            "name" -> name = value
                            "version" -> version = value
                            "description" -> description = value
                            "author" -> author = value
                            "enabled" -> isEnabled = value.toBoolean()
                            "auto_generated" -> isAutoGenerated = value.toBoolean()
                            "source" -> sourceUrl = value
                            "permissions" -> {
                                val split = value.split(',').map(String::trim).filter(String::isNotBlank)
                                permissions.addAll(split)
                            }
                        }
                    }
                }
            }
        }

        val instructions = if (bodyStartIndex < lines.size) {
            lines.subList(bodyStartIndex, lines.size).joinToString("\n").trim()
        } else {
            ""
        }

        val scriptFile = baseDir?.let { File(it, "run.sh").takeIf(File::isFile)?.absolutePath }
        val testScriptFile = baseDir?.let { File(it, "test.sh").takeIf(File::isFile)?.absolutePath }

        return SkillDefinition(
            id = id,
            name = name,
            version = version,
            description = description.ifBlank { name },
            instructions = instructions,
            allowedPermissions = permissions,
            scriptFile = scriptFile,
            testScriptFile = testScriptFile,
            isEnabled = isEnabled,
            isAutoGenerated = isAutoGenerated,
            author = author,
            sourceUrl = sourceUrl,
        )
    }

    fun saveSkill(skill: SkillDefinition, scriptContent: String? = null, testScriptContent: String? = null): File {
        val dir = File(skillsDir, skill.id).apply { mkdirs() }
        val skillFile = File(dir, "SKILL.md")

        val frontmatter = buildString {
            appendLine("---")
            appendLine("name: \"${skill.name.replace("\"", "\\\"")}\"")
            appendLine("version: \"${skill.version}\"")
            appendLine("description: \"${skill.description.replace("\"", "\\\"")}\"")
            appendLine("author: \"${skill.author}\"")
            appendLine("enabled: ${skill.isEnabled}")
            appendLine("auto_generated: ${skill.isAutoGenerated}")
            if (skill.allowedPermissions.isNotEmpty()) {
                appendLine("permissions: \"${skill.allowedPermissions.joinToString(", ")}\"")
            }
            if (!skill.sourceUrl.isNullOrBlank()) {
                appendLine("source: \"${skill.sourceUrl}\"")
            }
            appendLine("---")
            appendLine()
            appendLine(skill.instructions)
        }

        skillFile.writeText(frontmatter)

        if (!scriptContent.isNullOrBlank()) {
            File(dir, "run.sh").apply {
                writeText(scriptContent)
                setExecutable(true)
            }
        }

        if (!testScriptContent.isNullOrBlank()) {
            File(dir, "test.sh").apply {
                writeText(testScriptContent)
                setExecutable(true)
            }
        }

        skillCache[skill.id] = skill
        return dir
    }

    fun evolveSkill(
        skill: SkillDefinition,
        scriptContent: String? = null,
        testScriptContent: String? = null,
        testRunner: (testScript: File) -> Boolean,
    ): Boolean {
        val targetDir = File(skillsDir, skill.id)
        val backupDir = File(skillsDir, ".backup_${skill.id}_${System.currentTimeMillis()}")

        if (targetDir.exists()) {
            targetDir.copyRecursively(backupDir, overwrite = true)
        }

        try {
            saveSkill(skill.copy(isAutoGenerated = true), scriptContent, testScriptContent)
            val testFile = File(targetDir, "test.sh")

            val passed = if (testFile.isFile) {
                testRunner(testFile)
            } else {
                true
            }

            if (!passed) {
                targetDir.deleteRecursively()
                if (backupDir.exists()) {
                    backupDir.copyRecursively(targetDir, overwrite = true)
                }
                loadSkill(targetDir) // restore cached state
                return false
            }

            return true
        } catch (e: Exception) {
            targetDir.deleteRecursively()
            if (backupDir.exists()) {
                backupDir.copyRecursively(targetDir, overwrite = true)
            }
            loadSkill(targetDir) // restore cached state
            return false
        } finally {
            if (backupDir.exists()) {
                backupDir.deleteRecursively()
            }
        }
    }

    fun deleteSkill(id: String): Boolean {
        skillCache.remove(id)
        val dir = File(skillsDir, id)
        return if (dir.exists()) dir.deleteRecursively() else false
    }

    fun toggleSkill(id: String, enabled: Boolean): Boolean {
        val dir = File(skillsDir, id)
        val skill = skillCache[id] ?: loadSkill(dir) ?: return false
        saveSkill(skill.copy(isEnabled = enabled))
        return true
    }
}
