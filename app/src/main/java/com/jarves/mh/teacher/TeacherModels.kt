package com.jarves.mh.teacher

import java.util.UUID

data class Concept(
    val id: String = UUID.randomUUID().toString(),
    val subject: String,
    val name: String,
    val description: String = "",
    val mastery: Float = 0.0f,
    val pKnown: Float = 0.1f,
    val misconceptions: List<String> = emptyList(),
    val attempts: Int = 0,
    val correctCount: Int = 0,
    val lastPracticedMillis: Long = 0L,
) {
    val isMastered: Boolean get() = mastery >= 0.85f && attempts >= 3
}

